-- 004: вход через внешние сервисы (Google, Яндекс) вместо одного поля users.vk_id.
-- Одна запись = «этот пользователь входит через этого провайдера под таким внешним id».
CREATE TABLE IF NOT EXISTS user_identities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider    VARCHAR(20)  NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    email       VARCHAR(255),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (provider, external_id),                 -- один внешний аккаунт — один профиль
    UNIQUE (user_id, provider)                      -- у профиля один аккаунт каждого провайдера
);

-- Вход через VK убран; если кто-то успел войти через него, привязку не теряем
INSERT INTO user_identities (user_id, provider, external_id)
SELECT id, 'vk', vk_id FROM users WHERE vk_id IS NOT NULL
ON CONFLICT DO NOTHING;

DROP INDEX IF EXISTS uq_users_vk_id;
ALTER TABLE users DROP COLUMN IF EXISTS vk_id;
