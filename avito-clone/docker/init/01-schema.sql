-- Схема БД доски объявлений (PostgreSQL 16).
-- Выполняется автоматически при первом старте контейнера db.
SET client_encoding = 'UTF8';

-- Пользователи --------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name          VARCHAR(100) NOT NULL,
    phone         VARCHAR(32),                                  -- показывается по кнопке «Показать телефон»
    role          VARCHAR(5)   NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    is_blocked    SMALLINT     NOT NULL DEFAULT 0 CHECK (is_blocked IN (0, 1)),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Категории -----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(80) NOT NULL UNIQUE,
    icon  VARCHAR(16) NOT NULL DEFAULT '📦'                     -- эмодзи для полосы категорий
);

-- Объявления ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ads (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id      INTEGER      REFERENCES categories (id) ON DELETE SET NULL,   -- NULL, если категорию удалили
    title            VARCHAR(120) NOT NULL,
    description      TEXT         NOT NULL,
    price            BIGINT       NOT NULL DEFAULT 0 CHECK (price >= 0),           -- в рублях; 0 = «Бесплатно»
    city             VARCHAR(80)  NOT NULL,
    status           VARCHAR(8)   NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'blocked')),
    rejection_reason TEXT,                                                         -- причина от модератора
    views            INTEGER      NOT NULL DEFAULT 0 CHECK (views >= 0),
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP                -- обновляется приложением
);
CREATE INDEX IF NOT EXISTS idx_ads_status_created ON ads (status, created_at);
CREATE INDEX IF NOT EXISTS idx_ads_user_status    ON ads (user_id, status);
CREATE INDEX IF NOT EXISTS idx_ads_category       ON ads (category_id);
CREATE INDEX IF NOT EXISTS idx_ads_city           ON ads (city);
CREATE INDEX IF NOT EXISTS idx_ads_price          ON ads (price);

-- Фото объявлений (первое по id — обложка) ----------------------------------
CREATE TABLE IF NOT EXISTS ad_images (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_id    INTEGER      NOT NULL REFERENCES ads (id) ON DELETE CASCADE,
    filename VARCHAR(100) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ad_images_ad ON ad_images (ad_id);

-- Сообщения покупателей продавцам -------------------------------------------
CREATE TABLE IF NOT EXISTS messages (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_id        INTEGER   NOT NULL REFERENCES ads (id)   ON DELETE CASCADE,
    from_user_id INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    to_user_id   INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    body         TEXT      NOT NULL,
    is_read      SMALLINT  NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_to   ON messages (to_user_id, is_read, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_from ON messages (from_user_id, created_at);
