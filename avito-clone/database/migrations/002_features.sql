-- Пользователи ------------------------------------------------------------------
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;            -- VK может не отдать email
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;    -- вход только через VK — пароля нет
ALTER TABLE users ADD COLUMN IF NOT EXISTS vk_id         VARCHAR(32);
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_url    VARCHAR(500);
ALTER TABLE users ADD COLUMN IF NOT EXISTS about         TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMP;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_vk_id ON users (vk_id) WHERE vk_id IS NOT NULL;

-- Характеристики объявлений -----------------------------------------------------
ALTER TABLE ads ADD COLUMN IF NOT EXISTS attributes JSONB NOT NULL DEFAULT '{}'::jsonb;
CREATE INDEX IF NOT EXISTS idx_ads_attributes ON ads USING GIN (attributes);

-- Описание характеристик по категориям (авто: марка/год/пробег, техника: бренд/состояние …)
CREATE TABLE IF NOT EXISTS category_attributes (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER     NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    code        VARCHAR(40) NOT NULL CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    label       VARCHAR(80) NOT NULL,
    type        VARCHAR(10) NOT NULL CHECK (type IN ('text', 'number', 'select')),
    unit        VARCHAR(16),                                   -- «км», «м²», «лет» …
    options     JSONB       NOT NULL DEFAULT '[]'::jsonb,      -- варианты для type = select
    min_value   NUMERIC,                                       -- границы для type = number
    max_value   NUMERIC,
    required    SMALLINT    NOT NULL DEFAULT 0 CHECK (required IN (0, 1)),
    filterable  SMALLINT    NOT NULL DEFAULT 0 CHECK (filterable IN (0, 1)),
    sort_order  INTEGER     NOT NULL DEFAULT 0,
    UNIQUE (category_id, code)
);

-- Избранное -----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS favorites (
    user_id    INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    ad_id      INTEGER   NOT NULL REFERENCES ads (id)   ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, ad_id)
);
CREATE INDEX IF NOT EXISTS idx_favorites_ad ON favorites (ad_id, created_at);

-- Отзывы о продавцах -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reviews (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id  INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    author_id  INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating     SMALLINT  NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body       TEXT      NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (seller_id, author_id),
    CHECK (seller_id <> author_id)
);

-- Статистика: уникальные просмотры (один «человек» = один viewer_key на объявление) ---------
CREATE TABLE IF NOT EXISTS ad_views (
    ad_id      INTEGER     NOT NULL REFERENCES ads (id) ON DELETE CASCADE,
    viewer_key VARCHAR(40) NOT NULL,                           -- 'u<id>' для вошедшего, 'v<cookie>' для гостя
    first_seen TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ad_id, viewer_key)
);
CREATE INDEX IF NOT EXISTS idx_ad_views_day ON ad_views (ad_id, first_seen);

-- Контакты: показан телефон (уникально на человека)
CREATE TABLE IF NOT EXISTS ad_contacts (
    ad_id      INTEGER     NOT NULL REFERENCES ads (id) ON DELETE CASCADE,
    viewer_key VARCHAR(40) NOT NULL,
    type       VARCHAR(10) NOT NULL CHECK (type IN ('phone')),
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ad_id, viewer_key, type)
);
CREATE INDEX IF NOT EXISTS idx_ad_contacts_day ON ad_contacts (ad_id, created_at);

-- Чат: диалоги (на каждое объявление — свой диалог с каждым покупателем) -----------------
CREATE TABLE IF NOT EXISTS conversations (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_id           INTEGER   NOT NULL REFERENCES ads (id)   ON DELETE CASCADE,
    buyer_id        INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    seller_id       INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (ad_id, buyer_id),
    CHECK (buyer_id <> seller_id)
);
CREATE INDEX IF NOT EXISTS idx_conversations_buyer  ON conversations (buyer_id, last_message_at);
CREATE INDEX IF NOT EXISTS idx_conversations_seller ON conversations (seller_id, last_message_at);

CREATE TABLE IF NOT EXISTS chat_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id INTEGER   NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id       INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    body            TEXT      NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at         TIMESTAMP                                   -- NULL = не прочитано получателем
);
CREATE INDEX IF NOT EXISTS idx_chat_messages_conv   ON chat_messages (conversation_id, id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_unread ON chat_messages (conversation_id, sender_id) WHERE read_at IS NULL;

-- Перенос старой плоской переписки (таблица messages) в диалоги
WITH pairs AS (
    SELECT m.ad_id, a.user_id AS seller_id, m.created_at,
           CASE WHEN m.from_user_id = a.user_id THEN m.to_user_id ELSE m.from_user_id END AS buyer_id
    FROM messages m JOIN ads a ON a.id = m.ad_id
)
INSERT INTO conversations (ad_id, buyer_id, seller_id, created_at, last_message_at)
SELECT ad_id, buyer_id, seller_id, MIN(created_at), MAX(created_at)
FROM pairs
WHERE buyer_id <> seller_id
GROUP BY ad_id, buyer_id, seller_id
ON CONFLICT (ad_id, buyer_id) DO NOTHING;

INSERT INTO chat_messages (conversation_id, sender_id, body, created_at, read_at)
SELECT c.id, m.from_user_id, m.body, m.created_at, CASE WHEN m.is_read = 1 THEN m.created_at END
FROM messages m
JOIN ads a ON a.id = m.ad_id
JOIN conversations c ON c.ad_id = m.ad_id
                    AND c.buyer_id = CASE WHEN m.from_user_id = a.user_id THEN m.to_user_id ELSE m.from_user_id END
ORDER BY m.id;

DROP TABLE messages;

-- Журнал действий администраторов ------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    INTEGER REFERENCES users (id) ON DELETE SET NULL,
    actor_name  VARCHAR(100),                                   -- имя на момент действия (переживёт удаление аккаунта)
    action      VARCHAR(40) NOT NULL,                           -- ad.approve, user.block, category.create …
    target_type VARCHAR(20),
    target_id   INTEGER,
    details     JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_target  ON audit_log (target_type, target_id);
