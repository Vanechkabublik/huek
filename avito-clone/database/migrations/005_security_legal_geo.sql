# 1. Какие данные мы собираем
- Данные аккаунта: имя, адрес электронной почты, номер телефона (по желанию), фото профиля и текст «о себе».
- Данные входа через Яндекс или Google: идентификатор аккаунта, имя, подтверждённый адрес электронной почты и фото профиля. Пароли от этих сервисов нам не передаются.
- Содержимое объявлений: тексты, фотографии, видеообзоры, цена, город, характеристики, предпочтительный способ связи.
