# 2. Для чего мы используем данные
- Создание и обслуживание аккаунта, публикация и модерация объявлений, работа чата.
- Безопасность: защита от мошенничества, спама и злоупотреблений, блокировка нарушителей, в том числе по IP-адресу.
- Статистика и аналитика работы Сайта в обобщённом виде.
- Выполнение требований законодательства.

# 3. Кому мы передаём данные
Мы не продаём персональные данные. Для входа через Яндекс или Google данные передаются этим сервисам по вашему действию. Для определения города по геопозиции координаты (без привязки к аккаунту) отправляются в сервис OpenStreetMap Nominatim. Данные могут быть предоставлены по законному требованию уполномоченных органов.

